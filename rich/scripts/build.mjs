/**
 * Reproducible build of the two plugin halves.
 *
 *   Host   : src/host/index.ts   -> lib/index.js   (Node ESM, no runtime deps)
 *   Client : src/client/index.ts -> lib/client.js  (browser CJS wrapped in the
 *            documented `window.__ModuleLoader__.load({ id, factory })` table)
 *
 * React is never bundled: `react` and `react/jsx-runtime` stay external and are
 * resolved from the DSH browser module table at runtime. Harness packages are
 * type-only in this plugin and never reach the artifacts.
 *
 * Usage: node scripts/build.mjs
 */
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { mkdir, readFile, rm, stat } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const libDir = join(root, 'lib')
const PACKAGE_NAME = 'dsh-rich-response'
const CLIENT_BANNER = 'window.__ModuleLoader__.load({ id: '
  + JSON.stringify(PACKAGE_NAME)
  + ', factory: (require) => { var module = { exports: {} }; var exports = module.exports;'
const CLIENT_FOOTER = 'return module.exports; } });'

function fail(message) {
  console.error('build: ' + message)
  process.exitCode = 1
  throw new Error(message)
}

async function buildHost() {
  await build({
    absWorkingDir: root,
    entryPoints: ['src/host/index.ts'],
    outfile: 'lib/index.js',
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// dsh-rich-response host half (generated by scripts/build.mjs)' },
  })
}

async function buildClient() {
  await build({
    absWorkingDir: root,
    entryPoints: ['src/client/index.ts'],
    outfile: 'lib/client.js',
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: ['chrome110', 'firefox110', 'safari16'],
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/*'],
    define: { 'process.env.NODE_ENV': '"production"' },
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: CLIENT_BANNER },
    footer: { js: CLIENT_FOOTER },
  })
}

async function verifyArtifacts() {
  const client = await readFile(join(libDir, 'client.js'), 'utf8')
  const host = await readFile(join(libDir, 'index.js'), 'utf8')
  if (!client.startsWith(CLIENT_BANNER)) fail('client bundle does not start with the __ModuleLoader__ handoff')
  if (!client.trimEnd().endsWith(CLIENT_FOOTER)) fail('client bundle does not end with the factory close')
  if (!client.includes('id: ' + JSON.stringify(PACKAGE_NAME))) fail('client bundle id mismatch')
  if (!client.includes('module.exports = __toCommonJS(')) fail('client bundle lost the CJS export assignment')
  if (client.includes('require("react-dom') || client.includes("require('react-dom")) fail('client bundle must not require react-dom')
  if (!client.includes('require("react")')) fail('client bundle is expected to require react from the module table')
  const hostImports = [...host.matchAll(/^import\s.*?from\s+"([^"]+)"/gm)].map(match => match[1])
  const forbidden = hostImports.filter(specifier => !specifier.startsWith('node:'))
  if (forbidden.length > 0) fail('host bundle imports non-builtin modules: ' + forbidden.join(', '))
  if (host.includes('@deepseek-ai/')) fail('host bundle must not reference harness package specifiers')
  const clientStat = await stat(join(libDir, 'client.js'))
  const hostStat = await stat(join(libDir, 'index.js'))
  return {
    clientBytes: clientStat.size,
    hostBytes: hostStat.size,
    clientHash: createHash('sha256').update(client).digest('hex'),
  }
}

await rm(libDir, { recursive: true, force: true })
await mkdir(libDir, { recursive: true })
await buildHost()
await buildClient()
const sizes = await verifyArtifacts()
console.log('build: host   lib/index.js  ' + sizes.hostBytes + ' bytes')
console.log('build: client lib/client.js ' + sizes.clientBytes + ' bytes')
console.log('build: sha256(client)=' + sizes.clientHash)
